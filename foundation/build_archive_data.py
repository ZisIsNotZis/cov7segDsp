"""Keep the browser's research library tied to the original machine-readable results."""
import json
from pathlib import Path

from .fonts import DOC_DEC, DOC_HEX, OPT_DEC, MIN_FLIP_DEC, TOP0_DEC, MIN_MISMATCH_DEC


def main():
    root = Path(__file__).resolve().parents[1]
    foundation = json.loads((root / 'foundation/results/foundation.json').read_text(encoding='utf-8'))
    opt = json.loads((root / 'foundation/results/font_opt.json').read_text(encoding='utf-8'))
    channels = json.loads((root / 'foundation/results/channels.json').read_text(encoding='utf-8'))
    names = [('doc_dec', '原始笔记 · 数字', DOC_DEC), ('opt_dec', '最小距离候选 · 数字', OPT_DEC),
             ('min_flip_dec', '最少改段候选 · 数字', MIN_FLIP_DEC), ('top0_dec', '保留拓扑候选 · 数字', TOP0_DEC),
             ('min_mismatch_dec', '仅保拓扑的反例 · 数字', MIN_MISMATCH_DEC), ('doc_hex', '原始笔记 · 十六进制', DOC_HEX)]
    fonts = []
    for key, name, glyphs in names:
        score = foundation['fonts']['scores'][key]
        fonts.append({'id': key, 'name': name, 'glyphs': glyphs, 'flips': foundation['fonts']['flips'][key],
                      'mean': score['mean'], 'minimum': score['min'], 'topology': score['topology_mismatches'],
                      'nearest': score['nearest_mismatches']})
    cases = [('lr', 0, 'off', True, '左右任一侧，无故障'), ('all', 0, 'off', False, '四侧任一，方向未知，无故障'),
             ('both-lr', 0, 'off', True, '左右同时，无故障'), ('lr', 1, 'off', True, '左右任一 + 至多一段坏灭'),
             ('all', 1, 'off', True, '四侧任一 + 至多一段坏灭'), ('lr', 1, 'flip', True, '左右任一 + 至多一次翻转')]
    summary = []
    for mode, budget, fault, known, name in cases:
        row = {'name': name}
        for task in ('detection', 'correction'):
            result = next(c for c in channels['cases'] if c['covers'] == mode and c['budget'] == budget
                          and c['fault'] == fault and c['cover_known'] == known and c['task'] == task)
            row[task] = result['capacity']['value']
        summary.append(row)
    data = {'schema': 1, 'seven': foundation['seven_seg'], 'families': list(foundation['families'].values()), 'channels': summary,
            'fonts': fonts, 'hexNearest': {'status': opt['hex_nearest']['status'],
             'minimumViolations': opt['hex_min_nearest_violations']['nearest_violations']},
            'source': ['foundation/results/foundation.json', 'foundation/results/font_opt.json', 'foundation/results/channels.json', 'foundation/fonts.py']}
    dest = root / 'lab/archive-data.js'
    dest.write_text('/* Generated by python -m foundation.build_archive_data. */\n'
                    + 'globalThis.SignalArchive=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'Built research archive: {dest}')


if __name__ == '__main__':
    main()
