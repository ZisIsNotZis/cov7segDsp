"""Build the browser's compact capacity data from the canonical research JSON."""
import json
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    data = json.loads((root / 'foundation/results/channels.json').read_text(encoding='utf-8'))
    rows = [{"mode": c["covers"], "known": c["cover_known"], "fault": c["fault"],
             "budget": c["budget"], "goal": "detect" if c["task"] == "detection" else "correct",
             **{k: v for k, v in c["capacity"].items() if k in ("status", "value", "lower", "upper")}}
            for c in data['cases']]
    payload = json.dumps({"schema": 1, "rows": rows}, ensure_ascii=False, separators=(',', ':'))
    output = root / 'lab/research.js'
    output.write_text('/* Generated by python -m foundation.build_channel_data; do not edit. */\n'
                      + 'globalThis.SignalResearch=' + payload + ';\n', encoding='utf-8')
    print(f'Built {len(rows)} browser capacity records: {output}')


if __name__ == '__main__':
    main()
